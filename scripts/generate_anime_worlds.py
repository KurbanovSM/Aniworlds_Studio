def _slug(text: str) -> str:
    value = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return value or "entry"


def _global_kind(identifier: str, name: str, description: str) -> CreatureKindDraft:
    cognition = "animal" if identifier == "aot-kind-01" else "sapient"
