def main() -> None:
    catalogs = load_global_catalogs(CATALOG_PATH)
    human = next(item for item in catalogs.creature_kinds if item.id == "human")
    human.description = "Обычный разумный человек без автоматически предполагаемых сверхъестественных способностей."
    human.physical_features = ["Человеческое телосложение"]
    section_ids = {meta["section"] for meta in WORLD_META.values()}
    prefixes = {"sl", "aot", "opm", "jjk"}
    catalogs.equipment_sections = [item for item in catalogs.equipment_sections if item.id not in section_ids]
    catalogs.equipment = [item for item in catalogs.equipment if not any(item.id.startswith(f"{prefix}-") for prefix in prefixes)]
    catalogs.creature_kinds = [item for item in catalogs.creature_kinds if not any(item.id.startswith(f"{prefix}-kind-") for prefix in prefixes)]
    catalogs.groups = [item for item in catalogs.groups if not any(item.id.startswith(f"{prefix}-group-") for prefix in prefixes)]
    for key, meta in WORLD_META.items():
        prefix = {"solo": "sl", "aot": "aot", "opm": "opm", "jjk": "jjk"}[key]
        catalogs.equipment_sections.append(EquipmentSectionDraft(meta["section"], meta["name"].split(":")[0]))
        catalogs.equipment.extend(_equipment(prefix, meta["section"], meta["name"].split(":")[0], meta))
        catalogs.creature_kinds.extend(
            _global_kind(f"{prefix}-kind-{index:02d}", name, f"{name} из мира «{meta['name']}».")
            for index, name in enumerate(meta["kinds"], 1)
        )
        catalogs.groups.extend(
            _global_group(f"{prefix}-group-{index:02d}", name)
            for index, name in enumerate(meta["groups"], 1)
        )
    validate_global_catalogs(catalogs)
    worlds = [_build_world(key, catalogs) for key in WORLD_META]
    for world in worlds:
        validate_foundation(world)
        validate_world_catalog_references(world, catalogs)
    save_global_catalogs(catalogs, CONTENT, replace_existing=True)
    for world in worlds:
        target = CONTENT / "worlds" / f"{world.id}.draft.json"
        if target.exists():
            target.unlink()
        save_draft(world, target)
        print(f"CREATED {target.relative_to(ROOT)}: {len(world.characters)} characters, {len(world.locations)} locations")
    print(f"CATALOG: {len(catalogs.equipment_sections)} sections, {len(catalogs.equipment)} items")


if __name__ == "__main__":
    main()
