def _character_items(prefix: str, name: str, index: int) -> list[dict[str, int | str]]:
    if prefix == "opm" and name == "Сайтама":
        return [
            {"item_id": item_id, "quantity": 1}
            for item_id in (
                "opm-clothing-01",
                "opm-clothing-10",
                "opm-clothing-17",
                "opm-clothing-22",
                "opm-clothing-28",
            )
        ]
    return [
        {"item_id": f"{prefix}-weapon-{((index - 1) % 25) + 1:02d}", "quantity": 1},
        *_outfit_items(prefix, index),
    ]


